/**
 * Tema "console escuro" da LedBlock. Sem dynamic color — a marca aparece igual em
 * todo aparelho. [darkTheme] vem da preferência do usuário (Config → Tema) ou do
 * sistema. Também acerta a cor dos ícones da barra de status conforme o tema.
 */
@Composable
fun PainelOfertasTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colors = if (darkTheme) DarkColors else LightColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            val controller = WindowCompat.getInsetsController(window, view)
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colors,
        typography = AppTypography,
        shapes = AppShapes,
        content = content,
    )
}
